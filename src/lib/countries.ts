/**
 * Country presets for the tax and pension calculators: a single employee with no dependants,
 * using the rules in force for the stated tax year (researched November 2026). Rules change
 * with every budget, so each preset is a starting point the user can still edit.
 *
 * All amounts are annual, in the country's own currency.
 */
import type { Contribution, TaxBracket, TaxCredit } from './finance';

export type CountryPreset = {
  code: string;
  name: string;
  flag: string;
  currency: string;
  region: 'africa' | 'world';
  /** A representative annual salary used to prefill the calculators. */
  typicalSalary: number;
  tax: {
    year: string;
    allowance: number;
    allowanceLabel?: string;
    brackets: TaxBracket[];
    contributions: Contribution[];
    expenseDeduction?: TaxBracket[];
    expenseLabel?: string;
    credits?: TaxCredit[];
    surchargePct?: number;
    surchargeLabel?: string;
    alternativeBrackets?: TaxBracket[];
    notes: string[];
  };
  pension: {
    scheme: string;
    retireAge: number;
    employeePct: number;
    employerPct: number;
    /** Annual salary cap for contributions; 0 = none. */
    salaryCap: number;
    returnPct: number;
    inflationPct: number;
    salaryGrowthPct: number;
    notes: string[];
  };
};

export const CUSTOM_COUNTRY = 'custom';

/** Annual bands from `[from, rate%]` pairs. */
const annual = (...pairs: [number, number][]): TaxBracket[] => pairs.map(([from, rate]) => ({ from, rate }));
/** Annual bands from monthly `[from, rate%]` pairs, for countries that publish monthly PAYE tables. */
const monthly = (...pairs: [number, number][]): TaxBracket[] => pairs.map(([from, rate]) => ({ from: from * 12, rate }));
/** A flat-rate contribution, optionally capped at an annual salary of `cap`. */
const flat = (name: string, rate: number, opts: { cap?: number; deductible?: boolean } = {}): Contribution => ({
  name,
  deductible: !!opts.deductible,
  brackets: opts.cap ? [{ from: 0, rate }, { from: opts.cap, rate: 0 }] : [{ from: 0, rate }],
});

